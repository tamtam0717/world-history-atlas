import fs from 'fs';
const a = JSON.parse(fs.readFileSync('public/data/atlas.json','utf8'));
const year = +process.argv[2]; const isos = process.argv[3].split(',');
const pol = a.polities.map(p=>p.id);
const groups = {};
a.pieceIds.forEach((id,i)=>{ const iso=id.split('-')[0]; if(!isos.includes(iso)) return;
  let st=null; for (const s of a.pieceTimelines[i]) if (s[0]<=year) st=s;
  const k = st? `${a.regions[st[4]].id} => ${pol[st[1]]}${st[2]>=0?'/'+pol[st[2]]:''} ${a.certainty[st[3]]}`:'none';
  (groups[k] ||= []).push(id);});
for (const [k,v] of Object.entries(groups)) console.log(k, v.length, v.length<12? v.join(' '):'');
